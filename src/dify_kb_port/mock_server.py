"""Practice mock of the Dify 1.20.0 Knowledge (service) API. NOT a real Dify server.

Routes, response fields, limits and error texts follow the 1.20.0 sources (behaviour only, no
code copied), checked 2026-11-18:
  api/controllers/service_api/dataset/{dataset,document,segment,metadata}.py
  api/fields/segment_fields.py
  api/core/rag/index_processor/processor/paragraph_index_processor.py
It reproduces the behaviours that matter for moving a knowledge base: page limit of 100,
`has_more = page * limit < total`, custom separator handling (only the two characters
backslash-n are interpreted), re-splitting of long chunks, asynchronous indexing, chunk edits
refused until a document is "completed", and optional injected faults.
"""
from __future__ import annotations

import json
import re
import threading
import uuid
from dataclasses import dataclass
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

DEFAULT_KEY = "dataset-mock"
GENERATED_ANSWER = "(answer generated by the mock)"


@dataclass
class Faults:
    """Switches the tests flip to make the mock misbehave like a real, busy server."""

    rate_limit: int = 0  # answer the next N requests with 429 + Retry-After: 2
    reject_segment_ops: int = 0  # answer the next N chunk writes with 400 "Document is not completed."
    create_500_after: int | None = None  # after N created documents every create-by-text returns 500
    index_polls: int = 0  # a new document stays "indexing" for N indexing-status polls
    retokenize_limit: int | None = None  # server splits chunks longer than N words (tokenizer mismatch)
    has_more: str = "correct"  # correct | always_false | always_true
    page_cap: int | None = None  # server silently lowers `limit` (the has_more bug of #41775)
    overlap_pages: bool = False  # repeat the last item of the previous page (#30113)


class MockDify:
    def __init__(self, key: str = DEFAULT_KEY, host: str = "127.0.0.1", port: int = 0):
        self.key = key
        self.faults = Faults()
        self.requests: list[tuple[str, str]] = []
        self.limits_seen: list[int] = []  # every `limit` a client asked for, before the server capped it
        self.create_text_calls = 0
        self.datasets: dict[str, dict] = {}
        self.documents: dict[str, dict] = {}
        self.segments: dict[str, dict] = {}
        self.fields: dict[str, dict] = {}
        self._batches: dict[str, str] = {}
        self._lock = threading.Lock()
        mock = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args: object) -> None:  # keep test and demo output clean
                pass

            def _run(self) -> None:
                length = int(self.headers.get("Content-Length") or 0)
                raw = self.rfile.read(length) if length else b""
                try:
                    body = json.loads(raw) if raw else {}
                except ValueError:
                    body = {}
                if not isinstance(body, dict):  # a JSON list or string body is answered as "missing fields"
                    body = {}
                with mock._lock:
                    status, payload, headers = mock.handle(self.command, self.path, self.headers.get("Authorization", ""), body)
                data = b"" if payload is None else json.dumps(payload, ensure_ascii=False).encode("utf-8")
                self.send_response(status)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                for k, v in (headers or {}).items():
                    self.send_header(k, v)
                self.end_headers()
                self.wfile.write(data)

            do_GET = do_POST = do_PATCH = do_DELETE = _run

        self._server = ThreadingHTTPServer((host, port), Handler)
        self._server.daemon_threads = True
        self._thread: threading.Thread | None = None

    # -- lifecycle -------------------------------------------------------
    @property
    def url(self) -> str:
        host, port = self._server.server_address[:2]
        return f"http://{host}:{port}/v1"

    def start(self) -> "MockDify":
        self._thread = threading.Thread(target=self._server.serve_forever, kwargs={"poll_interval": 0.05}, daemon=True)
        self._thread.start()
        return self

    def stop(self) -> None:
        self._server.shutdown()
        self._server.server_close()
        if self._thread:
            self._thread.join(timeout=5)

    def __enter__(self) -> "MockDify":
        return self.start()

    def __exit__(self, *exc: object) -> None:
        self.stop()

    # -- helpers ---------------------------------------------------------
    def _id(self) -> str:
        return str(uuid.uuid4())

    @staticmethod
    def _err(status: int, code: str, message: str):
        return status, {"code": code, "message": message, "status": status}, None

    def write_requests(self) -> list[tuple[str, str]]:
        return [r for r in self.requests if r[0] in ("POST", "PATCH", "DELETE")]

    def _page(self, items: list[dict], q: dict):
        page = max(1, int(q.get("page", ["1"])[0]))
        limit = min(int(q.get("limit", ["20"])[0]), 100)
        self.limits_seen.append(int(q.get("limit", ["20"])[0]))
        if self.faults.page_cap:
            limit = min(limit, self.faults.page_cap)
        total = len(items)
        start = (page - 1) * limit
        if self.faults.overlap_pages and page > 1:
            start -= 1
        data = items[start:page * limit]
        has_more = page * limit < total
        if self.faults.has_more == "always_false":
            has_more = False
        elif self.faults.has_more == "always_true":
            has_more = True
        return {"data": data, "has_more": has_more, "limit": limit, "total": total, "page": page}

    def _split(self, text: str, rule: dict | None, form: str) -> list[str]:
        rule = rule or {}
        if rule.get("mode") == "custom":
            seg = (rule.get("rules") or {}).get("segmentation") or {}
            sep = str(seg.get("separator", "\\n\\n")).replace("\\n", "\n")  # only backslash-n is interpreted
            max_tokens = int(seg.get("max_tokens", 500))
        else:
            sep, max_tokens = "\n\n", 500
        limit = self.faults.retokenize_limit or max_tokens
        out: list[str] = []
        for part in text.split(sep):
            if not part.strip():
                continue
            words = part.split(" ")
            if len(words) <= limit:
                out.append(part)
            else:  # the server re-splits what it considers too long
                out.extend(" ".join(words[i:i + limit]) for i in range(0, len(words), limit))
        return out

    def _segment_view(self, seg: dict) -> dict:
        # sign_content mimics the real field: content with short-lived signed file URLs that must never be stored
        return {**seg, "tokens": len(seg["content"].split()), "word_count": len(seg["content"]),
                "sign_content": seg["content"] + " https://files.example.invalid/f.png?timestamp=1&sign=abc"}

    def _doc_view(self, doc: dict) -> dict:
        view = {k: v for k, v in doc.items() if not k.startswith("_")}
        view["indexing_status"] = "completed" if doc["_polls"] <= 0 else "indexing"
        return view

    def _segments_of(self, doc_id: str) -> list[dict]:
        return sorted((s for s in self.segments.values() if s["document_id"] == doc_id), key=lambda s: s["position"])

    def _check_segment_write(self, doc_id: str):
        doc = self.documents[doc_id]
        if self.faults.reject_segment_ops > 0:
            self.faults.reject_segment_ops -= 1
            return self._err(400, "invalid_param", "Document is not completed.")
        if doc["_polls"] > 0:
            return self._err(400, "invalid_param", "Document is not completed.")
        if not doc["enabled"]:
            return self._err(400, "invalid_param", "Document is disabled.")
        return None

    # -- request dispatch ------------------------------------------------
    def handle(self, method: str, raw_path: str, auth: str, body: dict):
        url = urlparse(raw_path)
        path = url.path.removeprefix("/v1")
        q = parse_qs(url.query)
        self.requests.append((method, path))
        if self.faults.rate_limit > 0:
            self.faults.rate_limit -= 1
            return 429, {"code": "too_many_requests", "message": "Too many requests", "status": 429}, {"Retry-After": "2"}
        if auth != f"Bearer {self.key}":
            return self._err(401, "unauthorized", "Access token is invalid")
        try:
            return self._route(method, path, q, body)
        except KeyError:
            return self._err(404, "not_found", f"{path}: not found")

    def _route(self, method: str, path: str, q: dict, body: dict):
        if path == "/datasets":
            if method == "GET":
                return 200, self._page(list(self.datasets.values()), q), None
            if method == "POST":
                if not body.get("name"):
                    return self._err(400, "invalid_param", "name is required")
                ds = {"id": self._id(), "name": body["name"], "provider": "vendor",
                      "indexing_technique": body.get("indexing_technique", "high_quality"), "permission": "only_me",
                      "embedding_model": "mock-embedding", "embedding_model_provider": "mock", "embedding_available": True,
                      "document_count": 0}
                self.datasets[ds["id"]] = ds
                return 200, ds, None
        m = re.fullmatch(r"/datasets/([\w-]+)", path)
        if m and method == "GET":
            ds = self.datasets[m[1]]
            return 200, {**ds, "document_count": sum(1 for d in self.documents.values() if d["dataset_id"] == m[1])}, None
        m = re.fullmatch(r"/datasets/([\w-]+)/documents", path)
        if m and method == "GET":
            self.datasets[m[1]]
            docs = [self._doc_view(d) for d in self.documents.values() if d["dataset_id"] == m[1]]
            return 200, self._page(docs, q), None
        m = re.fullmatch(r"/datasets/([\w-]+)/document/create[-_]by[-_]text", path)
        if m and method == "POST":
            return self._create_document(m[1], body)
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/status/(enable|disable|archive|un_archive)", path)
        if m and method == "PATCH":
            for doc_id in body.get("document_ids", []):
                doc = self.documents[doc_id]
                if m[2] in ("enable", "disable"):
                    doc["enabled"] = m[2] == "enable"
                else:
                    doc["archived"] = m[2] == "archive"
                    doc["enabled"] = doc["enabled"] and not doc["archived"]
            return 200, {"result": "success"}, None
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/metadata", path)
        if m and method == "POST":
            for op in body.get("operation_data", []):
                self.documents[op["document_id"]]["doc_metadata"] = [
                    {"id": x["id"], "name": x["name"], "type": self.fields[x["id"]]["type"], "value": x.get("value")}
                    for x in op["metadata_list"]]
            return 200, {"result": "success"}, None
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/([\w-]+)/indexing-status", path)
        if m and method == "GET":
            doc = self.documents[self._batches[m[2]]]
            if doc["_polls"] > 0:
                doc["_polls"] -= 1
            status = "completed" if doc["_polls"] <= 0 else "indexing"
            total = len(self._segments_of(doc["id"]))
            return 200, {"data": [{"id": doc["id"], "indexing_status": status,
                                   "completed_segments": total if status == "completed" else 0, "total_segments": total}]}, None
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/([\w-]+)", path)
        if m and method == "DELETE":
            doc = self.documents.pop(m[2])
            for sid in [s["id"] for s in self._segments_of(doc["id"])]:
                del self.segments[sid]
            return 204, None, None
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/([\w-]+)/segments", path)
        if m:
            doc = self.documents[m[2]]
            if method == "GET":
                out = self._page([self._segment_view(s) for s in self._segments_of(m[2])], q)
                out["doc_form"] = doc["doc_form"]
                return 200, out, None
            if method == "POST":
                return self._create_segments(m[2], body)
        m = re.fullmatch(r"/datasets/([\w-]+)/documents/([\w-]+)/segments/([\w-]+)", path)
        if m:
            seg = self.segments[m[3]]
            blocked = self._check_segment_write(m[2])
            if blocked:
                return blocked
            if method == "DELETE":
                del self.segments[m[3]]
                return 204, None, None
            if method == "POST":
                for k, v in (body.get("segment") or {}).items():
                    if k in ("content", "answer", "keywords", "enabled", "summary") and v is not None:
                        seg[k] = v
                return 200, {"data": self._segment_view(seg), "doc_form": self.documents[m[2]]["doc_form"]}, None
        m = re.fullmatch(r"/datasets/([\w-]+)/metadata", path)
        if m:
            self.datasets[m[1]]
            if method == "GET":
                fields = [{"id": f["id"], "name": f["name"], "type": f["type"], "count": 0}
                          for f in self.fields.values() if f["dataset_id"] == m[1]]
                return 200, {"doc_metadata": fields, "built_in_field_enabled": False}, None
            if method == "POST":
                if body.get("type") not in ("string", "number", "time") or not body.get("name"):
                    return self._err(400, "invalid_param", "type and name are required")
                if any(f["name"] == body["name"] and f["dataset_id"] == m[1] for f in self.fields.values()):
                    return self._err(400, "invalid_param", "The metadata name already exists.")
                field = {"id": self._id(), "dataset_id": m[1], "type": body["type"], "name": body["name"]}
                self.fields[field["id"]] = field
                return 200, {k: field[k] for k in ("id", "type", "name")}, None
        return self._err(404, "not_found", f"{method} {path}: no such route in the mock")

    def _create_document(self, dataset_id: str, body: dict):
        self.datasets[dataset_id]
        if self.faults.create_500_after is not None and self.create_text_calls >= self.faults.create_500_after:
            return self._err(500, "internal_error", "mock: injected failure")
        if not body.get("name") or not str(body.get("text", "")).strip():
            return self._err(400, "invalid_param", "name and text are required")
        rule = body.get("process_rule")
        if (rule or {}).get("mode") == "custom":
            seg = (rule.get("rules") or {}).get("segmentation") or {}
            if not 50 <= int(seg.get("max_tokens", 500)) <= 4000:
                return self._err(400, "invalid_param", "Custom segment length should be between 50 and 4000.")
        self.create_text_calls += 1
        form = body.get("doc_form", "text_model")
        doc_id = self._id()
        batch = uuid.uuid4().hex
        self.documents[doc_id] = {"id": doc_id, "dataset_id": dataset_id, "name": body["name"], "doc_form": form,
                                  "enabled": True, "archived": False, "doc_metadata": [],
                                  "_polls": self.faults.index_polls}
        self._batches[batch] = doc_id
        for pos, chunk in enumerate(self._split(body["text"], rule, form), start=1):
            self._add_segment(doc_id, pos, chunk, GENERATED_ANSWER if form == "qa_model" else None, [])
        return 200, {"document": self._doc_view(self.documents[doc_id]), "batch": batch}, None

    def _add_segment(self, doc_id: str, position: int, content: str, answer: str | None, keywords: list) -> dict:
        seg = {"id": self._id(), "position": position, "document_id": doc_id, "content": content, "answer": answer,
               "keywords": keywords, "enabled": True, "status": "completed", "child_chunks": [], "summary": None}
        self.segments[seg["id"]] = seg
        return seg

    def _create_segments(self, doc_id: str, body: dict):
        blocked = self._check_segment_write(doc_id)
        if blocked:
            return blocked
        form = self.documents[doc_id]["doc_form"]
        existing = self._segments_of(doc_id)
        position = (existing[-1]["position"] if existing else 0) + 1
        out = []
        for item in body.get("segments", []):
            if not item.get("content"):
                return self._err(400, "invalid_param", "content is required")
            if form == "qa_model" and not item.get("answer"):
                return self._err(400, "invalid_param", "Answer is required for qa_model documents.")
            out.append(self._segment_view(self._add_segment(doc_id, position, item["content"], item.get("answer"),
                                                            item.get("keywords") or [])))
            position += 1
        return 200, {"data": out, "doc_form": form}, None
